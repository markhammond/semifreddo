using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Semifreddo.Generators;

/// <summary>
/// Emits the shared surface of the persistent topological orders (<c>ImmPkTopoOrder</c>, <c>ImmLeveledPkTopoOrder</c>) into
/// any <c>readonly partial struct X&lt;N, TSentinel&gt;</c> marked <c>[TopoOrderSurface]</c> that implements
/// <c>ITopoOrderStorage&lt;X&lt;N, TSentinel&gt;, N, TSentinel, TEntry&gt;</c> (and adds <c>IRefEnumerable</c>). The entry policy comes from that interface;
/// everything specific to one type (summary, level members) stays hand-written in its own partial declaration.
/// One template, so the two types' common members cannot drift; the public API baseline catches any surface change.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TopoOrderGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "Semifreddo.TopoOrderSurfaceAttribute";

    private static readonly DiagnosticDescriptor Invalid = new(
        "IMMGEN001", "Invalid [TopoOrderSurface] target", "{0}", "Semifreddo.Generators", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static c => c.AddSource("TopoOrderSurfaceAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            static (node, _) => node is StructDeclarationSyntax,
            static (ctx, _) => Model.From((INamedTypeSymbol)ctx.TargetSymbol));

        context.RegisterSourceOutput(models, static (spc, m) =>
        {
            if (m.Error is not null) spc.ReportDiagnostic(Diagnostic.Create(Invalid, Location.None, m.Error));
            else spc.AddSource($"{m.Name}.TopoOrderSurface.g.cs", SourceText.From(Render(m), Encoding.UTF8));
        });
    }

    /// <summary>Equatable (cache-friendly) description of one target: no symbols or syntax retained.</summary>
    private sealed record Model(string Namespace, string Name, string Entry, bool Leveled, string? Error)
    {
        public static Model From(INamedTypeSymbol t)
        {
            var ns = t.ContainingNamespace.IsGlobalNamespace ? "" : t.ContainingNamespace.ToDisplayString();
            Model Fail(string why) => new(ns, t.Name, "", false, $"{t.ToDisplayString()}: {why}");

            if (!t.IsReadOnly) return Fail("must be a readonly partial struct");
            if (t.TypeParameters.Length != 2 || t.TypeParameters[0].Name != "N" || t.TypeParameters[1].Name != "TSentinel")
                return Fail("type parameters must be <N, TSentinel>");
            var storage = t.Interfaces.FirstOrDefault(i => i.Name == "ITopoOrderStorage" && i.TypeArguments.Length == 4
                && SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], t));
            if (storage is null) return Fail($"must implement ITopoOrderStorage<{t.Name}<N, TSentinel>, N, TSentinel, TEntry>");
            var entry = storage.TypeArguments[3];
            var leveled = entry.GetMembers("TracksLevels").Length == 1 && entry.Name == "WithLevels";
            return new(ns, t.Name, entry.Name, leveled, null);
        }
    }

    private static string Render(Model m)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/> by Semifreddo.Generators.TopoOrderGenerator from [TopoOrderSurface]\n");
        sb.Append("#nullable enable\nusing System.Collections;\nusing System.Diagnostics.CodeAnalysis;\n\n");
        if (m.Namespace.Length > 0) sb.Append("namespace ").Append(m.Namespace).Append(";\n\n");
        sb.Append("readonly partial struct ").Append(m.Name).Append("<N, TSentinel> : IRefEnumerable<N, TopoEnumerator<N, TSentinel>>\n{\n");
        sb.Append(Template
            .Replace("{TYPE}", m.Name)
            .Replace("{ENTRY}", m.Entry)
            .Replace("{LEVELWORD}", m.Leveled ? " and level" : "")
            .Replace("{LEVELWORD2}", m.Leveled ? " and the levels" : ""));
        sb.Append("}\n");
        return sb.ToString();
    }

    private const string AttributeSource = """
        // <auto-generated/> by Semifreddo.Generators.TopoOrderGenerator
        namespace Semifreddo;

        /// <summary>Generates the shared topological-order surface into this partial struct (build time only).</summary>
        [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false)]
        [global::System.Diagnostics.Conditional("SEMIFREDDO_GENERATOR_ATTRIBUTES")]
        internal sealed class TopoOrderSurfaceAttribute : global::System.Attribute { }
        """;

    private const string Template = """"
    internal readonly TopoCore<N, TSentinel, {ENTRY}> Core;

    internal {TYPE}(TopoCore<N, TSentinel, {ENTRY}> core) => Core = core;
    static {TYPE}<N, TSentinel> ITopoOrderStorage<{TYPE}<N, TSentinel>, N, TSentinel, {ENTRY}>.Wrap(TopoCore<N, TSentinel, {ENTRY}> core) => new(core);
    static TopoCore<N, TSentinel, {ENTRY}> ITopoOrderStorage<{TYPE}<N, TSentinel>, N, TSentinel, {ENTRY}>.Unwrap({TYPE}<N, TSentinel> order) => order.Core;

    public static {TYPE}<N, TSentinel> Empty => default;
    public int Count => Core.Count;
    public bool IsEmpty => Core.IsEmpty;
    public bool IsSameAs({TYPE}<N, TSentinel> other) => Core.IsSameAs(other.Core);
    public bool Contains(N node) => Core.Contains(node);

    /// <summary>Position of <paramref name="node"/> in the order: comparable within the same version only.</summary>
    public bool TryGetRank(N node, out long rank) => Core.TryGetRank(node, out rank);

    /// <summary>True if <paramref name="a"/> comes before <paramref name="b"/> in the order.</summary>
    public bool Precedes(N a, N b) => Core.Precedes(a, b);

    /// <summary>Appends a node (last in the order); no-op if present. The sentinel value is rejected.</summary>
    public {TYPE}<N, TSentinel> Add(N node) => new(Core.Add(node));

    /// <summary>Removes a node; never invalidates the order of the others.</summary>
    public {TYPE}<N, TSentinel> Remove(N node) => new(Core.Remove(node));

    /// <summary>Gives <paramref name="newNode"/> the position{LEVELWORD} of <paramref name="oldNode"/> (rename).</summary>
    public {TYPE}<N, TSentinel> Replace(N oldNode, N newNode) => new(Core.Replace(oldNode, newNode));

    /// <summary>Restores the order after <paramref name="graph"/> gained from→to. Throws <see cref="DagCycleException{N}"/>.</summary>
    public {TYPE}<N, TSentinel> AddEdge<TGraph>(TGraph graph, N from, N to) where TGraph : IDagAdjacency<N>, allows ref struct
        => new(Core.AddEdge(graph, from, to));

    /// <summary>Restores the order after <paramref name="graph"/> gained from→to; on a cycle returns false, this
    /// unchanged, and one cycle (first == last). O(1) when the edge already agrees with the order{LEVELWORD2}.</summary>
    public bool TryAddEdge<TGraph>(TGraph graph, N from, N to, out {TYPE}<N, TSentinel> result, [NotNullWhen(false)] out N[]? cycle)
        where TGraph : IDagAdjacency<N>, allows ref struct
    {
        bool ok = Core.TryAddEdge(graph, from, to, out var r, out cycle);
        result = new(r);
        return ok;
    }

    /// <summary>Probe: false on a cycle without building it (allocation-free failure path).</summary>
    public bool TryAddEdge<TGraph>(TGraph graph, N from, N to, out {TYPE}<N, TSentinel> result)
        where TGraph : IDagAdjacency<N>, allows ref struct
    {
        bool ok = Core.TryAddEdge(graph, from, to, out var r);
        result = new(r);
        return ok;
    }

    /// <summary>Restores the order after <paramref name="graph"/> gained all <paramref name="edges"/> (e.g. an
    /// <see cref="ImmDag{N, A, V}.Scope.AddedEdges"/> batch): few out-of-order edges run Pearce–Kelly edge by edge,
    /// many run one Kahn re-sort of the affected window. On a cycle returns false, this unchanged, and one cycle.</summary>
    public bool TryAddEdges<TGraph>(TGraph graph, ReadOnlySpan<(N From, N To)> edges, out {TYPE}<N, TSentinel> result, [NotNullWhen(false)] out N[]? cycle)
        where TGraph : IDagAdjacency<N>, allows ref struct
    {
        bool ok = Core.TryAddEdges(graph, edges, out var r, out cycle);
        result = new(r);
        return ok;
    }

    /// <summary>Probe form of the batch overload (no cycle on failure).</summary>
    public bool TryAddEdges<TGraph>(TGraph graph, ReadOnlySpan<(N From, N To)> edges, out {TYPE}<N, TSentinel> result)
        where TGraph : IDagAdjacency<N>, allows ref struct
    {
        bool ok = Core.TryAddEdges(graph, edges, out var r);
        result = new(r);
        return ok;
    }

    /// <summary>
    /// Cost-weighted bottom levels for critical-path list scheduling: <c>bottom[n] = cost(n) + max bottom[successor]</c>,
    /// one reverse pass over the order, O(V + E). Run ready nodes in descending bottom level to shorten the makespan.
    /// Costs are supplied per call (static estimates or measured averages). Returns the critical path length;
    /// <paramref name="bottom"/> is cleared and refilled (reuse it across ticks).
    /// </summary>
    public double ComputeBottomLevels<TGraph>(TGraph graph, Func<N, double> cost, Dictionary<N, double> bottom)
        where TGraph : IDagAdjacency<N>, allows ref struct
        => Core.ComputeBottomLevels(graph, cost, bottom);

    /// <summary>Batch of edits on a thread-local pooled transient (which must not escape <paramref name="batch"/>).</summary>
    public {TYPE}<N, TSentinel> Mutate<TArg>(TArg arg, Action<Transient, TArg> batch) where TArg : allows ref struct
    {
        var t = Transient.Rent(Core);
        try { batch(t, arg); return t.ToPersistent(); }
        finally { Transient.Return(t); }
    }

    public Transient ToTransient()
    {
        var t = new Transient();
        t.Reset(this);
        return t;
    }

    /// <summary>Copies the nodes in topological order into <paramref name="destination"/> (length &gt;= Count). Allocation-free.</summary>
    public void CopyTo(Span<N> destination)
    {
        if (destination.Length < Count) throw new ArgumentException("Destination is shorter than Count.", nameof(destination));
        int i = 0;
        foreach (var n in this) destination[i++] = n;
    }

    /// <summary>The nodes in topological order. An instance method, so it binds ahead of LINQ's <c>ToArray</c> (no boxing).</summary>
    public N[] ToArray()
    {
        var a = new N[Count];
        CopyTo(a);
        return a;
    }

    /// <summary>Nodes in topological order (span-chunked scan, holes skipped).</summary>
    public TopoEnumerator<N, TSentinel> GetEnumerator() => Core.GetEnumerator();
    IEnumerator<N> IEnumerable<N>.GetEnumerator() => Core.GetCursor();
    IEnumerator IEnumerable.GetEnumerator() => Core.GetCursor();

    // Removal holes live in the slot vector: no contiguous span and no positional access, so callers enumerate.
    bool IRefEnumerable<N, TopoEnumerator<N, TSentinel>>.TryGetSpan(out ReadOnlySpan<N> span)
    {
        span = default;
        return Count == 0;
    }

    bool IRefEnumerable<N, TopoEnumerator<N, TSentinel>>.TryCopyTo(int index, Span<N> destination)
    {
        RefEnumerable.CopyLength(Count, index, destination.Length);
        return false;
    }

    /// <summary>Mutable view; the shared surface is <see cref="TopoTransient{TSelf, TOrder, N, TSentinel, TEntry}"/>.</summary>
    public sealed partial class Transient : TopoTransient<Transient, {TYPE}<N, TSentinel>, N, TSentinel, {ENTRY}>;

"""";
}
